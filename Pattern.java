public class Pattern {
    public static void main(String[] args) {
        int n=5;
        for(int i=1;i<=n;i++){
            for(int j=1;j<=i;j++){
                System.out.print("*");
            }
            System.out.println();
        }

        int n1=4;
        for(int i=1;i<=n1;i++){
            for(int j=1;j<=i;j++){
            System.out.print(j);}
            System.out.println();
        }
        int n2=4;
        for(int i=1;i<=n2;i++){
            for(int j=1;j<=i;j++){
            System.out.print(i);}
            System.out.println();
        }

          
    }
    
}
