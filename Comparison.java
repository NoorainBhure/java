public class Comparison {
    public static void main(String[] args) {
        //equal to
        boolean resultEqual=(5==5);
        System.out.println("Equal to :"+resultEqual);
        //Notequal to
        boolean resultNotEqual=(15!=5);
        System.out.println("Not Equal to :"+resultNotEqual);
       
        //greater to
        boolean resultGreater=(15>5);
        System.out.println("Greater to :"+resultGreater);
        //less than
        boolean resultLess=(15<8);
        System.out.println("Less than :"+resultLess);
        //greater than or eqal to
        boolean resultGreaterEqual=(15>=5);
        System.out.println("Greater Equal to :"+resultGreaterEqual);
        //Less than or eqal to
        boolean resultLessEqual=(15<=5);
        System.out.println("Less than Equal to :"+resultLessEqual);
    }
    
}
